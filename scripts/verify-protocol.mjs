#!/usr/bin/env node
/**
 * verify-protocol.mjs — DSH_CMD 双向管道协议四方机械化对照（RM-02 / R-13）。
 *
 * AGENTS.md §1 双向管道协议同步红线: 帧格式与命令名变更必须同步
 *   `src-tauri/src/managers/node.rs` 分发表 ↔ `src/managers/tauri-shell.ts`
 *   （sendDshCmd）↔ `src/models/pipe.ts`（DshCmdName）。手工同步已发生两次漂移
 *   （DshCmdName 缺 set_desktop_icon，三轮独立命中；get_workspace_path 已发送
 *   未分发），本脚本把该约束机械化为只读门禁：
 *
 *   corner ① node.rs `dispatch_dsh_cmd` match 臂名集合（活动协议命令）
 *   corner ② host 侧 DSH_CMD 上行发送点实参命令名集合
 *            （src/managers/tauri-shell.ts invoke() +
 *             src/controllers/shell-runtime.ts / tray-pipe.ts 的 sendDshCmd）
 *   corner ③ src/models/pipe.ts `DshCmdName` 联合类型成员集合
 *   corner ④ ACL invoke 命令名集合
 *            （src-tauri/permissions/autogenerated/*.toml 的 commands.allow，
 *             且被 src-tauri/capabilities/default.json 的 allow-* 引用）
 *
 * 比较语义：
 *   - corners ①②③ 必须两两相等（protocol 集合）；任一 corner 缺任一命令 → FAIL
 *     （“四方缺一 FAIL”），并输出逐命令对比表。
 *   - corner ④ 是 ACL 覆盖检查：protocol 集合中每个「经 IPC invoke 执行」的命令
 *     必须在 ACL 允许列表里。dispatch_page_event 走 win.eval 通道、不是 invoke
 *     命令（node.rs 注释明示，页面不 invoke 它），列为已知例外 EVAL_ONLY，仅 INFO。
 *   - 已知例外（协议活动面之外，检出即 INFO 提示、不 FAIL）：
 *       · node.rs 旧名兼容臂 applyTheme / applySize / notify（warn+ignore）；
 *       · tauri-shell.ts 的 get_workspace_path 死桩发送（D4：页面主动上报工作区，
 *         invoke 恒返回 null，node.rs 无分发臂、也不进 DshCmdName ——
 *         R2-3 发现8 / R1-3 发现1）。
 *
 * 解析方式（按任务约定）：
 *   · node.rs match 臂：行锚定文本扫描 `"command_name" =>`，支持 `"a" | "b" =>`
 *     多模式臂；
 *   · TS 联合类型：正则提取块内 `'...'` 引号成员；
 *   · capabilities：JSON 解析；autogenerated TOML：文本提取 [[permission]] 块。
 *
 * 本脚本只读源码文件，不执行构建、不触碰 DSH_HOME、不写任何产物。
 * 注意：DshCmdName 的 `set_desktop_icon` 由 T-B 轨补入；本脚本不硬编码任何
 * 命令名、完全从源码解析，最终态下四方应全绿。
 *
 * Usage: node scripts/verify-protocol.mjs
 * Exit code 0 = all PASS; 1 = FAIL (protocol drifted, fix before release).
 *
 * @module dsh-hub/scripts/verify-protocol
 * @category Helper
 */

import { existsSync, readFileSync, readdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO_ROOT = dirname(dirname(fileURLToPath(import.meta.url)))

const results = [] // { name, ok, detail }
function check(name, ok, detail) {
  results.push({ name, ok, detail })
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${detail ? ` — ${detail}` : ''}`)
}
function info(name, detail) {
  console.log(`INFO  ${name}${detail ? ` — ${detail}` : ''}`)
}

// ── 已知例外（协议活动面之外）──────────────────────────────────────────────

/** node.rs 旧名兼容臂：warn + ignore，不是活动协议命令。 */
const LEGACY_COMPAT = new Set(['applyTheme', 'applySize', 'notify'])
/** tauri-shell 死桩发送：D4 页面主动上报，invoke 恒 null，无分发臂。 */
const KNOWN_STUB_SENDS = new Set(['get_workspace_path'])
/** 走 win.eval 而非 IPC invoke 的命令（node.rs 注释明示）。 */
const EVAL_ONLY = new Set(['dispatch_page_event'])

// ── corner ①: node.rs dispatch_dsh_cmd match 臂 ─────────────────────────────

const nodeRs = readFileSync(join(REPO_ROOT, 'src-tauri', 'src', 'managers', 'node.rs'), 'utf8')
// 行锚定：`"name" =>` 或 `"a" | "b" =>`（臂体内部不出现行首引号+=>，other 臂无引号）。
const ARM_RE = /^\s*("(?:[^"\\]|\\.)*"(?:\s*\|\s*"(?:[^"\\]|\\.)*")*)\s*=>/gm
const allArms = []
for (const m of nodeRs.matchAll(ARM_RE)) {
  for (const name of m[1].split('|')) allArms.push(name.trim().replace(/^"|"$/g, ''))
}
const corner1 = new Set(allArms.filter((a) => !LEGACY_COMPAT.has(a)))
const legacyArms = allArms.filter((a) => LEGACY_COMPAT.has(a))

// ── corner ②: host 侧 DSH_CMD 上行发送点实参命令名 ─────────────────────────

const SEND_FILES = [
  join(REPO_ROOT, 'src', 'managers', 'tauri-shell.ts'),
  join(REPO_ROOT, 'src', 'controllers', 'shell-runtime.ts'),
  join(REPO_ROOT, 'src', 'controllers', 'tray-pipe.ts'),
]
const sent = new Set()
for (const file of SEND_FILES) {
  const text = readFileSync(file, 'utf8')
  // tauri-shell.ts invoke('cmd', ...) / invoke<string>('cmd') — DSH_CMD 上行原语。
  for (const m of text.matchAll(/invoke(?:<[^>]*>)?\s*\(\s*'([^']+)'/g)) sent.add(m[1])
  // sendDshCmd({ cmd: 'name', ... })（shell-runtime / tray-pipe 两处实现）。
  for (const m of text.matchAll(/(?:deps\.)?sendDshCmd\(\s*\{\s*cmd:\s*'([^']+)'/g)) sent.add(m[1])
}
const stubSends = [...sent].filter((c) => KNOWN_STUB_SENDS.has(c))
const corner2 = new Set([...sent].filter((c) => !KNOWN_STUB_SENDS.has(c)))

// ── corner ③: pipe.ts DshCmdName 联合类型成员 ───────────────────────────────

/** 提取 `export type DshCmdName = ...` 块内的单引号成员（块到下一个 export 为止）。 */
function parseDshCmdNameMembers(pipeTs) {
  const typeStart = pipeTs.indexOf('export type DshCmdName')
  if (typeStart < 0) return null
  const afterHead = pipeTs.slice(typeStart + 'export type DshCmdName'.length)
  const relEnd = afterHead.search(/\nexport (type|interface|const|function|class)\b/)
  const block = (relEnd < 0 ? afterHead : afterHead.slice(0, relEnd))
    .replace(/\/\*[\s\S]*?\*\//g, '') // strip block-local comments
    .replace(/\/\/[^\n]*/g, '')
  return [...block.matchAll(/'([^']+)'/g)].map((m) => m[1])
}

const pipeTs = readFileSync(join(REPO_ROOT, 'src', 'models', 'pipe.ts'), 'utf8')
const members = parseDshCmdNameMembers(pipeTs)
if (members === null) {
  check('corner ③ DshCmdName type found', false, 'src/models/pipe.ts missing `export type DshCmdName`')
} else {
  check('corner ③ DshCmdName members parsed', members.length > 0, `members=${members.length}`)
}
const corner3set = new Set(members ?? [])

// ── corner ④: ACL invoke 命令名集合 ─────────────────────────────────────────

const autogenDir = join(REPO_ROOT, 'src-tauri', 'permissions', 'autogenerated')
const capsPath = join(REPO_ROOT, 'src-tauri', 'capabilities', 'default.json')
const missingAutogenRefs = []

/** identifier -> [commands] from autogenerated TOML [[permission]] blocks. */
const idToCommands = new Map()
if (existsSync(autogenDir)) {
  for (const file of readdirSync(autogenDir)) {
    if (!file.endsWith('.toml')) continue
    const text = readFileSync(join(autogenDir, file), 'utf8')
    for (const block of text.matchAll(/\[\[permission\]\][\s\S]*?(?=\[\[permission\]\]|$)/g)) {
      const idm = /identifier\s*=\s*"([^"]+)"/.exec(block[0])
      const cmdm = /commands\.allow\s*=\s*\[([^\]]*)\]/.exec(block[0])
      if (idm && cmdm) {
        idToCommands.set(idm[1], [...cmdm[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]))
      }
    }
  }
}

const aclSet = new Set()
if (existsSync(capsPath)) {
  const caps = JSON.parse(readFileSync(capsPath, 'utf8'))
  const allowRefs = (caps.permissions ?? []).filter(
    (p) => typeof p === 'string' && p.startsWith('allow-') && !p.includes(':'),
  )
  for (const ref of allowRefs) {
    const cmds = idToCommands.get(ref)
    if (!cmds) {
      missingAutogenRefs.push(ref)
      continue
    }
    for (const c of cmds) aclSet.add(c)
  }
}

// ── 输出与比较 ──────────────────────────────────────────────────────────────

const sorted = (s) => [...s].sort().join(', ')

console.log(`[verify-protocol] DSH_CMD 四方对照 @ ${new Date().toISOString()}\n`)
console.log(`corner ① node.rs dispatch_dsh_cmd arms (${corner1.size}): ${sorted(corner1)}`)
console.log(`corner ② host DSH_CMD send sites (${corner2.size}): ${sorted(corner2)}`)
console.log(`corner ③ DshCmdName union (${corner3set.size}): ${sorted(corner3set)}`)
console.log(`corner ④ ACL invoke commands (${aclSet.size}): ${sorted(aclSet)}`)
if (legacyArms.length) info('corner ① legacy compat aliases (warn+ignore, not protocol)', sorted(legacyArms))
if (stubSends.length) info('corner ② known dead-stub sends (D4, not protocol)', sorted(stubSends))
info('corner ④ eval-only commands (not IPC invoke, not in ACL)', sorted(EVAL_ONLY))

// ① ② ③ 两两相等（四方缺一 FAIL）
const protocolUnion = new Set([...corner1, ...corner2, ...corner3set])
const gaps = []
for (const cmd of protocolUnion) {
  const in1 = corner1.has(cmd)
  const in2 = corner2.has(cmd)
  const in3 = corner3set.has(cmd)
  if (!(in1 && in2 && in3)) gaps.push({ cmd, in1, in2, in3 })
}
if (gaps.length === 0) {
  check('三端协议集合一致（①②③ 缺一 FAIL）', true, `${protocolUnion.size} commands, all corners aligned`)
} else {
  const detail = gaps
    .map((g) => `${g.cmd}[①${g.in1 ? '✓' : '✗'} ②${g.in2 ? '✓' : '✗'} ③${g.in3 ? '✓' : '✗'}]`)
    .join(', ')
  check('三端协议集合一致（①②③ 缺一 FAIL）', false, `drift: ${detail}`)
}

// ④ ACL 覆盖：protocol 命令中经 invoke 执行的必须被 ACL 允许
if (missingAutogenRefs.length > 0) {
  check('ACL 覆盖（④）', false, `capabilities allow-* 引用无 autogenerated 定义: ${missingAutogenRefs.join(', ')}`)
} else {
  const aclMissing = []
  for (const cmd of protocolUnion) {
    if (EVAL_ONLY.has(cmd)) continue
    if (!aclSet.has(cmd)) aclMissing.push(cmd)
  }
  if (aclMissing.length > 0) {
    check('ACL 覆盖（④）', false, `protocol 命令未被 ACL 允许: ${aclMissing.join(', ')}`)
  } else {
    check('ACL 覆盖（④）', true, 'every invoke-backed protocol command is allowed in capabilities')
  }
}

// ── 逐命令对比表 ────────────────────────────────────────────────────────────

console.log('\ncommand                    | ①node.rs | ②sends | ③DshCmdName | ④ACL')
console.log('---------------------------|----------|--------|-------------|-----')
const tableCmds = new Set([...protocolUnion, ...aclSet])
for (const cmd of [...tableCmds].sort()) {
  const mark = (s) => (s.has(cmd) ? ' ✓' : ' ✗')
  console.log(`${cmd.padEnd(27)} |${mark(corner1)}|${mark(corner2)}|${mark(corner3set)}|${mark(aclSet)}`)
}

const failed = results.filter((r) => !r.ok)
console.log(`\n[verify-protocol] ${failed.length === 0 ? 'ALL PASS — protocol in sync' : `${failed.length} FAILED — protocol drifted`}`)
process.exit(failed.length === 0 ? 0 : 1)
